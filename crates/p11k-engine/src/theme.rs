//! Theme drawing: at the prompt hook the engine writes the theme header to the real terminal.
//!
//! Division of labor: the shell prints a prompt string made of header_rows blank lines, the
//! zero-width prompt-ready signal and the input-line prefix, so its geometry accounts for the
//! header lines. The engine does not parse ANSI from the pty output; it only passes bytes
//! through, strips the signal and positions the cursor:
//! - `prompt_start`: emitted on the `h` announcement, before the shell prints the prompt string.
//! - `redraw_header_cfg`: when the signal arrives, move up over the blank rows and fill in the
//!   real header (line content generated by [`crate::render::render_header_lines`] from the KDL
//!   config), then restore the cursor.
//! - `render_prompt`: repaint the input line's prefix on top of the one the shell drew (resize
//!   path only: the fresh prompt string is already on screen and this restores the styling).
//! - `render_header_cfg`: for the instant header only (engine has not spawned the shell yet),
//!   drawing the full header and prefix directly.

use std::io::{self, Write};

pub use crate::model::{GitStatus, HeaderInfo};

/// OSC 133 A: prompt start marker (shell integration). The engine emits it on the `h`
/// announcement (before the shell prints the prompt string); it is not repeated when the header
/// is filled in or redrawn.
pub fn prompt_start(out: &mut dyn Write) -> io::Result<()> {
    write!(out, "\x1b]133;A\x07")
}

/// Write the header content line by line, advancing to the start of the next line, and return
/// each line's **display width**. When content is wider than the terminal the terminal wraps it,
/// and the caller converts that width into the actual number of rows occupied (the instant
/// header must move up by it to erase).
fn header_body(
    out: &mut dyn Write,
    lines: &[crate::render::PaintedLine],
) -> io::Result<Vec<usize>> {
    let mut widths = Vec::with_capacity(lines.len());
    for line in lines {
        write!(out, "\r\x1b[K")?;
        out.write_all(line.text.as_bytes())?;
        write!(out, "\r\n")?;
        widths.push(line.width);
    }
    Ok(widths)
}

/// Render the full header from the KDL config (multiple lines, count set by the config):
/// OSC133A + line content. For the instant header only (engine has not spawned the shell and no
/// prompt string exists yet); the normal prompt cycle goes through "shell prints the blank rows
/// + signal, redraw_header_cfg fills them in" instead. Returns each line's display width.
pub fn render_header_cfg(
    out: &mut dyn Write,
    cols: usize,
    config: &crate::config::Config,
    info: &HeaderInfo,
    vcs: Option<&GitStatus>,
    vi_mode: crate::model::ViMode,
) -> io::Result<Vec<usize>> {
    prompt_start(out)?;
    let lines = crate::render::render_header_lines_with_widths(config, info, vcs, cols, vi_mode);
    header_body(out, &lines)
}

/// Fill in/redraw the header: save the input line cursor, move up to header line 1, redraw
/// line by line, restore. The number of rows moved up equals the configured header line count;
/// the input line is untouched. The shell has already printed that many blank lines as part of
/// the prompt string, so the real content is written over them, and `\x1b8` returns to the input
/// line cursor. Resize redraws and the first fill-in after the signal share this code.
///
/// `last` holds the lines the previous paint wrote. An asynchronous git result arrives after the
/// header was already painted with the previous result, so when the new lines match it the paint
/// would write the same bytes onto the same rows. `last` lets the call skip that paint. A caller
/// that must repaint regardless, because the rows were cleared in between, sets `last` to `None`
/// first; the call then paints and records the new lines.
///
/// Cursor save/restore uses the 7-bit `ESC 7` / `ESC 8` form of DECSC/DECRC rather than the
/// `CSI s` / `CSI u` aliases: nvim's built-in terminal (libvterm) implements only the 7-bit
/// form, so with the aliases the restore lands in the top-left corner and the whole prompt
/// window is painted on the wrong rows.
pub fn redraw_header_cfg(
    out: &mut dyn Write,
    cols: usize,
    config: &crate::config::Config,
    info: &HeaderInfo,
    vcs: Option<&GitStatus>,
    last: &mut Option<Vec<crate::render::PaintedLine>>,
    vi_mode: crate::model::ViMode,
) -> io::Result<()> {
    let lines = crate::render::render_header_lines_with_widths(config, info, vcs, cols, vi_mode);
    if last.as_ref() == Some(&lines) {
        return Ok(());
    }
    let n = lines.len().max(1);
    write!(out, "\x1b7\x1b[{}A", n)?;
    header_body(out, &lines)?;
    write!(out, "\x1b8")?;
    *last = Some(lines);
    Ok(())
}

/// Repaint the input line's prefix: save the cursor, `\r` back to the start of the input line to
/// draw `prefix`, restore the cursor.
///
/// Only the deferred resize repaint uses this. The shell has already printed the prompt string
/// with the prefix in it, so this is not what puts the prefix on screen in the normal path; it
/// restores the theme styling after zle reprints the prompt on a resize. `\e7` saves the cursor,
/// `\r` returns to column 0, and `\e8` restores the cursor, so a non-empty buffer is left alone
/// and nothing conflicts with zle's cursor model.
pub fn render_prompt(out: &mut dyn Write, prefix: &str) -> io::Result<()> {
    write!(out, "\x1b7\r{prefix}\x1b8")?;
    // OSC 133 B: prompt end marker, telling the terminal the cursor now rests at the input
    // position, so closing the window no longer asks to confirm a "running program" (aligns
    // with p10k _p9k_prompt_suffix).
    write!(out, "\x1b]133;B\x07")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_prompt_starts_with_cr() {
        let mut out = Vec::new();
        render_prompt(&mut out, "❯ ").unwrap();
        let s = String::from_utf8_lossy(&out);
        assert!(
            s.starts_with("\x1b7\r❯ "),
            "should save the cursor, go back to column 0 to draw the prefix, then restore the cursor"
        );
        assert!(
            s.ends_with("\x1b]133;B\x07"),
            "should end with the OSC 133 B marker (telling the terminal the prompt is ready)"
        );
    }

    /// An async git result that renders the same lines as the prompt-time paint must not write
    /// again: the bytes and the rows are identical. Clearing the cache forces the paint, which is
    /// what a caller does when the rows were cleared in between.
    #[test]
    fn redraw_paints_only_when_the_lines_change() {
        let config =
            crate::config::Config::parse("layout {\n    left { line { dir } }\n}\n").unwrap();
        let header = |cwd: &str| HeaderInfo {
            exit_code: Some(0),
            cwd: cwd.to_string(),
            exec_seconds: 0.0,
            exec_ms: None,
            jobs: 0,
            history: 0,
            pipestatus: Vec::new(),
        };
        let tmp = header("/tmp");
        let var = header("/var");

        let mut out = Vec::new();
        let mut last = None;
        redraw_header_cfg(
            &mut out,
            80,
            &config,
            &tmp,
            None,
            &mut last,
            crate::model::ViMode::Unreported,
        )
        .unwrap();
        let first = out.len();
        assert!(first > 0, "the first paint writes the header");

        redraw_header_cfg(
            &mut out,
            80,
            &config,
            &tmp,
            None,
            &mut last,
            crate::model::ViMode::Unreported,
        )
        .unwrap();
        assert_eq!(
            out.len(),
            first,
            "identical lines must not be painted again"
        );

        redraw_header_cfg(
            &mut out,
            80,
            &config,
            &var,
            None,
            &mut last,
            crate::model::ViMode::Unreported,
        )
        .unwrap();
        let second = out.len();
        assert!(second > first, "changed lines must repaint");

        last = None;
        redraw_header_cfg(
            &mut out,
            80,
            &config,
            &var,
            None,
            &mut last,
            crate::model::ViMode::Unreported,
        )
        .unwrap();
        assert!(out.len() > second, "an empty cache must force the paint");
    }
}
